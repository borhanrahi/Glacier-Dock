const lazyCache = new Map<string, LazyExoticComponent<ComponentType>>();

export function widgetMeta(id: string): WidgetMeta | null {
  return WIDGETS.find((widget) => widget.id === id) ?? null;
}

export function widgetComponent(id: string): LazyExoticComponent<ComponentType> | null {
  const loader = LOADERS[id];
  if (!loader) return null;
  const cached = lazyCache.get(id);
  if (cached) return cached;
  const component = lazy(loader);
  lazyCache.set(id, component);
  return component;
}

export function widgetsByCategory(category: WidgetCategory): WidgetMeta[] {
  return WIDGETS.filter((widget) => widget.category === category);
}

export function searchWidgets(query: string): WidgetMeta[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return WIDGETS;
  return WIDGETS.filter((widget) =>
    (widget.name + " " + widget.description + " " + widget.category)
      .toLowerCase()
      .includes(needle),
  );
}
